# מכניס את כל מגילת תענית (נוסח ורשה תרל"ד, דרך ספריא) ל-TANAKH_DATE_EVENTS: הימים הטובים + הסכוליון, ו"מאמר האחרון" (ימי התענית).
# מוחק רק רשומות מובנות שמקורן "מגילת תענית" ומחליף בנוסח המאומת. הרצה: python3 _עבודה/scripts/megillat-taanit.py <mt.json>
import json,re,sys
D=json.load(open(sys.argv[1],encoding='utf8')); M={o['m']:o['lines'] for o in D}
nk=lambda s: re.sub(r'[\u0591-\u05C7]','',s).strip()
MON={'סיוון':'סיון'}
# (חודש בספריא, שורה ראשית, ימים, כותרת). השורה שאחריה = הסבר (סכוליון)
T=[('ניסן',1,['א'],'הוקם התמיד משל ציבור — מראש חודש ניסן עד ח׳ בו'),('ניסן',3,['ח'],'נקבע חג השבועות כדברי חכמים — מח׳ בניסן עד סוף המועד'),
('אייר',0,['ז'],'חנוכת חומת ירושלים'),('אייר',2,['יד'],'שחיטת הפסח הקטן (פסח שני)'),('אייר',4,['כג'],'יצאו בני החקרא מירושלים'),('אייר',6,['כז'],'הוסרו העטרות (״כלילאי״) מיהודה ומירושלים'),
('סיוון',0,['יז'],'נכבש מגדל צור'),('סיוון',2,['טו','טז'],'גלו אנשי בית שאן ואנשי הבקעה'),('סיוון',4,['כה'],'הוסרו ה״דימוסנאי״ מיהודה ומירושלים'),
('תמוז',0,['יד'],'בטל ספר הגזרות'),('אב',0,['טו'],'זמן עצי הכהנים'),('אב',4,['כד'],'חזרו לדין התורה'),
('אלול',0,['ז'],'חנוכת חומת ירושלים'),('אלול',2,['יז'],'יצאו הרומאים מיהודה ומירושלים'),('אלול',4,['כב'],'חזרו להעניש את המשומדים'),
('תשרי',0,['ג'],'הוסרה הזכרת השם מן השטרות'),
('חשון',0,['כג'],'נסתר הסורג מן העזרה'),('חשון',2,['כה'],'נכבשה חומת שומרון'),('חשון',4,['כז'],'חזרה הסולת לעלות על המזבח'),
('כסלו',0,['ג'],'הוסרו הסימואות מן העזרה'),('כסלו',2,['ז'],'יום טוב'),('כסלו',4,['כא'],'יום הר גריזים'),('כסלו',6,['כה'],'חנוכה — שמונה ימים'),
('טבת',0,['כח'],'ישבה הכנסת על הדין'),
('שבט',0,['ב'],'יום טוב'),('שבט',3,['כב'],'בטלה העבודה שאמר השונא להכניס להיכל'),('שבט',5,['כח'],'נסתלק אנטיוכוס המלך מירושלים'),
('אדר',0,['ח','ט'],'יום תרועה על המטר'),('אדר',2,['יב'],'יום טוריינוס'),('אדר',4,['יג'],'יום ניקנור'),('אדר',6,['יד','טו'],'ימי הפורים'),
('אדר',8,['טז'],'התחילו לבנות את חומת ירושלים'),('אדר',10,['יז'],'קמו העמים על פליטת הסופרים והייתה הצלה'),('אדר',12,['כ'],'צמאו העם למטר וירד להם'),
('אדר',14,['כח'],'באה בשורה טובה שלא יעברו מדברי התורה')]
js=lambda s: json.dumps(s,ensure_ascii=False)
out=[]
for m,i,days,title in T:
    L=M[m]; main=nk(L[i]); exp=nk(L[i+1])
    if m=='אב' and i==0: main+=' '+nk(L[1]); exp=nk(L[2])
    mm=MON.get(m,m)
    for d in days:
        out.append(f'  {{ day:{js(d)}, month:{js(mm)}, event:{js(title)}, source:{js("מגילת תענית, "+mm)}, desc:{js("״"+main.rstrip(": ")+"״ — "+exp)} }},')
# מאמר האחרון — ימי התענית
last=nk(M['אדר'][-2]); body=last.split('עד הערב.',1)[1].split('אלו ימי תענית')[0]
HN={'א':1,'ב':2,'ג':3,'ד':4,'ה':5,'ו':6,'ז':7,'ח':8,'ט':9,'י':10,'כ':20}
WORD={'אחד':'א','חמשה':'ה','ששה':'ו','שבעה':'ז','עשרה':'י'}
MW={'ניסן':'ניסן','אייר':'אייר','סיון':'סיון','תמוז':'תמוז','אב':'אב','אלול':'אלול','תשרי':'תשרי','מרחשון':'חשון','כסליו':'כסלו','טבת':'טבת','שבט':'שבט','אדר':'אדר'}
cur=None;n=0
for sent in [x.strip(' :') for x in re.split(r'[.:]\s',body) if x.strip(' :')]:
    mt=re.match(r"^ב(אחד|חמשה|ששה|שבעה|עשרה|[א-ת\"']+?)\s+(?:ב(ניסן|אייר|סיון|תמוז|אב|אלול|תשרי|מרחשון|כסליו|טבת|שבט|אדר)|בו)\s+(.*)$",sent)
    if not mt:
        mt2=re.match(r'^בט"ב\s+(.*)$',sent)
        if mt2: day,cur,ev='ט','אב',mt2.group(1)
        else: print('דילוג:',sent[:40]); continue
    else:
        g=mt.group(1); day=WORD.get(g) or g.replace('"','').replace("'",'')
        if mt.group(2): cur=MW[mt.group(2)]
        ev=mt.group(3)
    if 'לא כתבו רבותינו' in ev: ev='יום תענית — "לא כתבו רבותינו על מה"'
    out.append(f'  {{ day:{js(day)}, month:{js(cur)}, event:{js(ev.strip())}, source:"מגילת תענית, מאמר האחרון (ימי תענית)", desc:"מן הימים ש״מתענין בהם״ לפי הרשימה שבסוף מגילת תענית." }},'); n+=1
p='guides/_shared/dates.js'; s=open(p,encoding='utf8').read()
i=s.index('const TANAKH_DATE_EVENTS = ['); j=s.index('\n];',i)
body=s[i:j].split('\n'); kept=[l for l in body if 'source:"מגילת תענית' not in l]
print('הוסרו',len(body)-len(kept),'| ימים טובים',len(out)-n,'| ימי תענית',n)
s=s[:i]+'\n'.join(kept)+'\n  // מגילת תענית — כל הימים (נוסח ורשה תרל״ד דרך ספריא), עם הנוסח וההסבר; נוצר ב-_עבודה/scripts/megillat-taanit.py\n'+'\n'.join(out)+s[j:]
open(p,'w',encoding='utf8').write(s)
