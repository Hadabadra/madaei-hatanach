async function publishUpcomingEvents(){
  if (_publishInFlight) return;
  _publishInFlight = true;
  try {
    await new Promise(r => setTimeout(r, PUBLISH_STARTUP_DELAY_MS + Math.floor(Math.random() * 10000)));
    await publishUpcomingEventsInner();
  }
  finally { _publishInFlight = false; }
}

async function publishUpcomingEventsInner(){
  if (!(window.Otzaria && Otzaria.call)) return;
  if (typeof eventsForToday !== 'function' || typeof todayHebrew !== 'function') return;

  // מריצים לכל היותר פעם ביום: פתיחת התוסף קוראת לפונקציה הזו בכל plugin.boot
  // (גם ברקע וגם בטאב הפעיל, ר' bridge.js/background.js) - בלי המגבלה הזו כל
  // פתיחה הייתה מוחקת ובונה מחדש את כל השנה מול היומן של אוצריא, גם כשכלום
  // לא השתנה.
  const todayIso = (() => { const n = new Date(); return n.getFullYear() + '-' + String(n.getMonth()+1).padStart(2,'0') + '-' + String(n.getDate()).padStart(2,'0'); })();
  const lastRun = await storageGetJson(PUBLISH_LAST_RUN_KEY);
  // ריצה שהושלמה היום — אין מה לעשות. ריצה שנקטעה היום (complete !== true)
  // ממשיכה מה-checkpoint: זול, כי רק מה שטרם פורסם ייכתב.
  const prevStateEarly = await storageGetJson(PUBLISHED_KEYS_KEY);
  const prevComplete = Array.isArray(prevStateEarly) ? true
    : !!(prevStateEarly && prevStateEarly.complete);
  if (lastRun === todayIso && prevComplete) return;
  // 3.3.2: ה-throttle נכתב *מיד*, לא בסוף. עד 3.3.1 הוא נכתב רק בסיום ריצה
  // מלאה — וריצה שנקטעה (סגירת האפליקציה באמצע) גרמה לכל עלייה להתחיל את
  // כל הסנכרון מחדש, שוב ושוב. הכתיבה-מראש גם סוגרת את המרוץ בין מופע הרקע
  // למופע הלשונית. ריצה שנקטעת מושלמת למחרת דרך הסנכרון הדיפרנציאלי למטה
  // (ה-checkpoint של kept שומר את מה שכבר פורסם).
  await storageSetJson(PUBLISH_LAST_RUN_KEY, todayIso);

  if (_churbanHebYear == null) _churbanHebYear = gregToHebDate(70, 7, 4).year;

  // 3.3.2 — קריאת ההעדפות גם כשאין uiPrefs גלובלי: מנוע הרקע (background.html)
  // לא טוען את shell/settings.js, ולכן עד כה uiPrefs היה undefined שם והבדיקות
  // למטה נפלו לברירת המחדל "פרסם הכל" — כיבוי בהגדרות נמחק מהיומן בטאב, ומנוע
  // הרקע החזיר את הכל ב-app.startup הבא (דווח בפורום על 3.3.1). קוראים ישירות
  // מאחסון אוצריא — אותו מקום ש-savePrefs (shell/settings.js) מגבה אליו.
  let pubPrefs = (typeof uiPrefs === 'object' && uiPrefs) ? uiPrefs : null;
  if (!pubPrefs) pubPrefs = await storageGetJson(PUBLISH_PREFS_KEY);
  if (!pubPrefs || typeof pubPrefs !== 'object') pubPrefs = {};
  const wantEvents  = pubPrefs.pubEvents  === true;
  const wantChurban = pubPrefs.pubChurban === true;
  // 3.3.2 — pubAhead/pubBack סוף־סוף בשימוש: עד כה ההגדרות "כמה זמן קדימה/אחורה"
  // נשמרו (shell/settings.js) אבל אף אחד לא קרא אותן, והקבועים 365/7 נשארו קשיחים.
  const lookAhead = (typeof pubPrefs.pubAhead === 'number' && isFinite(pubPrefs.pubAhead) && pubPrefs.pubAhead >= 1)
    ? Math.min(Math.floor(pubPrefs.pubAhead), 3650) : PUBLISH_LOOKAHEAD_DAYS;
  const lookBack = (typeof pubPrefs.pubBack === 'number' && isFinite(pubPrefs.pubBack) && pubPrefs.pubBack >= 0)
    ? Math.min(Math.floor(pubPrefs.pubBack), 3650) : PUBLISH_LOOKBACK_DAYS;

  const pad = (n) => String(n).padStart(2, '0');
  const isoOf = (d) => d.getFullYear() + '-' + pad(d.getMonth() + 1) + '-' + pad(d.getDate());
  const startsAtOf = (d) => {
    const tzMin = -d.getTimezoneOffset();
    const tz = (tzMin >= 0 ? '+' : '-') + pad(Math.floor(Math.abs(tzMin) / 60)) + ':' + pad(Math.abs(tzMin) % 60);
    return isoOf(d) + 'T00:00:00' + tz;
  };

  const items = []; // {key, payload}
  const base = new Date();
  // גם כששני המתגים כבויים הפונקציה ממשיכה לרוץ: items נשאר ריק, והלולאה על
  // prev למטה היא מה שמוחק מהיומן את כל מה שכבר פורסם.
  const spanEnd = (wantEvents || wantChurban) ? lookAhead : -lookBack;
  for (let off = -lookBack; off < spanEnd; off++){
    const d = new Date(base.getFullYear(), base.getMonth(), base.getDate() + off);
    const raw = gregToHebDate(d.getFullYear(), d.getMonth() + 1, d.getDate());
    const isLeap = isHebrewLeapYear(raw.year);
    const monthName = hebMonthNameOf(raw.month, isLeap);
    const dayLetters = numToHeb(raw.day);
    const churbanEl = elapsedSinceChurbanRaw(raw);
    const churbanTxt = churbanEl.years + ' שנה ' + churbanEl.months + ' חודשים ' + churbanEl.days + ' ימים לחורבן';
    const iso = isoOf(d), startsAt = startsAtOf(d);
    const dayLabel = dayLetters + '׳ ' + monthName + ' ' + hebYearStr(raw.year) + ' (' + gregDateStr(d) + ')';

    // אין קשר בין מאורעות התנ״ך/התלמוד לזמן שעבר מהחורבן - לכן churbanTxt לא
    // מופיע בתיאור שלהם (בניגוד לגרסה קודמת). מפתח ה"חורבן" מתחיל ב-z כדי
    // שיישאר אחרון בסדר לקסיקוגרפי אם היומן ממיין לפי key בין אירועי אותו יום.
    // (wantEvents/wantChurban נקבעים בכניסה לפונקציה — כולל בקונטקסט הרקע,
    // ר' ההערה על pubPrefs למעלה. כיבוי עדיין מריץ את הפרסום: ההרצה היא מה
    // שמוחק מהיומן את מה שכבר פורסם — הלולאה על prev למטה.)
    const events = wantEvents ? allDateEvents().filter(ev => monthMatchesEventMonth(monthName, ev.month) && dayMatchesEventDay(raw.day, ev.day)) : [];
    events.forEach((ev, i) => items.push({
      key: 'madaei:dailyEvent:' + iso + ':' + i,
      payload: { title: calendarSafeText(ev.event), startsAt, source: (typeof PLUGIN_DISPLAY_NAME !== 'undefined' ? PLUGIN_DISPLAY_NAME : 'עינים למקרא'), importance: 'low',
        // #99 (4.0.0): התיאור נושא את המאורע עצמו ואת המקור, לא רק את התאריך
        // #99 (4.7): שם ה׳ מוסתר גם בטקסט שנשלח ליומן, כמו בתצוגה שבתוסף
        description: calendarSafeText(ev.event + (ev.desc ? '\n\n' + ev.desc + '\n' : '') + (ev.source ? '\nמקור: ' + ev.source : '')) + '\n' + dayLabel
          + '\nמתוך ״ערך היום״ בתוסף ' + (typeof PLUGIN_DISPLAY_NAME !== 'undefined' ? PLUGIN_DISPLAY_NAME : 'עינים למקרא') }
    }));
    if (wantChurban) items.push({
      key: 'madaei:zChurban:' + iso,
      payload: { title: churbanTxt, startsAt, source: (typeof PLUGIN_DISPLAY_NAME !== 'undefined' ? PLUGIN_DISPLAY_NAME : 'עינים למקרא'), importance: 'low',
        description: dayLabel }
    });
  }

  // ---- סנכרון דיפרנציאלי (3.3.2) ----
  // עד 3.3.1 כל ריצה עשתה upsert לכל ~536 הפריטים מחדש (ובגל של עדכון-דאטה גם
  // מאות remove) — פעם ביום זה עבר בשקט, אבל בעליית האפליקציה זה מה שתקע אותה.
  // ה-payload של מפתח נתון דטרמיניסטי לגמרי (נגזר מהתאריך ומטבלת המאורעות),
  // ולכן מפתח שכבר פורסם בחתימת-דאטה זהה אינו זקוק ל-upsert חוזר. ביום רגיל
  // הדיף הוא ~2-3 פריטים (יום חדש נכנס לטווח, יום ישן יוצא); סנכרון מלא קורה
  // רק כשטבלת המאורעות עצמה השתנתה (חתימה שונה) — פעם אחת, אחרי עדכון גרסה.
  const djb2 = (s) => { let h = 5381; for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) >>> 0; return h.toString(36); };
  const dataSig = djb2(items.map(it => it.key + '|' + it.payload.title).join('\n'));
  const prevState = prevStateEarly;
  const prevKeys = Array.isArray(prevState) ? prevState
    : (prevState && Array.isArray(prevState.keys)) ? prevState.keys : [];
  const prevSig = (prevState && !Array.isArray(prevState)) ? prevState.sig : null;

  const newKeySet = new Set(items.map(it => it.key));
  const publishedSet = new Set(prevSig === dataSig ? prevKeys : []); // חתימה השתנתה => הכל טעון פרסום מחדש

  const kept = prevKeys.filter(k => newKeySet.has(k) && publishedSet.has(k));
  const saveState = (complete) => storageSetJson(PUBLISHED_KEYS_KEY, { sig: dataSig, keys: kept, complete: complete === true });

  for (const key of prevKeys){
    if (!newKeySet.has(key)){
      await Otzaria.call('publishedData.remove', { type: 'calendar.event', scope: 'global', key }).catch(()=>{});
    }
  }

  // checkpoint כל 50 פריטים: ריצה שנקטעת (סגירת האפליקציה) לא מאבדת את מה
  // שכבר פורסם, וההשלמה למחרת מתחילה מאיפה שנעצרה במקום מאפס.
  let sinceCheckpoint = 0;
  for (const it of items){
    if (publishedSet.has(it.key)) continue;
    const res = await Otzaria.call('publishedData.upsert', {
      type: 'calendar.event', scope: 'global', key: it.key, payload: it.payload
    }).catch(() => null);
    if (res && res.success){
      kept.push(it.key);
      if (++sinceCheckpoint >= 50){ sinceCheckpoint = 0; await saveState(false); }
    }
  }
  await saveState(true);
}

// ---- 4.3.0 — ״ערך היום״ לפי תאריך נתון (התאריך שנבחר ביומן של אוצריא,
// והתראות המערכת היומיות). todayHebrew/eventsForToday נשארים כמות שהם.
function hebrewOfDate(d){
  const raw = gregToHebDate(d.getFullYear(), d.getMonth() + 1, d.getDate());
  const isLeap = isHebrewLeapYear(raw.year);
  return { dayLetters: numToHeb(raw.day), monthName: hebMonthNameOf(raw.month, isLeap), raw: raw };
}
function eventsForDate(d){
  const t = hebrewOfDate(d);
  return allDateEvents().filter(ev => monthMatchesEventMonth(t.monthName, ev.month) && dayMatchesEventDay(t.raw.day, ev.day));
}
